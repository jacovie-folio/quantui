def force_floats(expr: str) -> str:
    """
    Ensures all numeric literals in the expression are treated as floats.
    For example, "4000/3" becomes "4000.0/3.0".
    """
    return re.sub(r'(?<!\.)\b(\d+)\b', r'\1.0', expr)


def closest_sum_with_breakdown(
    target: float,
    mode: str,  # 'above' or 'below'
    arr: Sequence[float] = arr,
    precision: int = 3
) -> Optional[Sequence[Tuple[float, int]]]:
    """
    Finds the closest sum using elements from `arr` that is either:
    - >= target (`mode='above'`)
    - <= target (`mode='below'`)

    Returns the breakdown as a list of (element, count) tuples.
    """
    assert mode in ('above', 'below'), "Mode must be 'above' or 'below'"

    scale = 10 ** precision
    int_arr = sorted(set(int(round(x * scale))
                     for x in arr))  # deduplicate + sort

    # Correctly determine the integer target based on the mode without premature rounding.
    if mode == 'above':
        int_target = math.ceil(target * scale)
        # Set a search limit high enough to find a combination. 2x the target is a reasonable heuristic.
        max_limit = int_target * 2
    else:  # mode == 'below'
        int_target = math.floor(target * scale)
        # For 'below' mode, we don't need to search beyond the target itself.
        max_limit = int_target

    dp = [False] * (max_limit + 1)
    dp[0] = True
    dp_trace = [None] * (max_limit + 1)

    for a in int_arr:
        for i in range(a, max_limit + 1):
            if dp[i - a] and not dp[i]:
                dp[i] = True
                dp_trace[i] = (i - a, a)

    if mode == 'above':
        closest = next(
            (i for i in range(int_target, max_limit + 1) if dp[i]), None)
    else:  # mode == 'below'
        closest = next((i for i in range(int_target, -1, -1) if dp[i]), None)

    if closest is None:
        return None

    # Reconstruct the path
    count_map = defaultdict(int)
    current = closest
    while current != 0:
        prev, used = dp_trace[current]
        count_map[used] += 1
        current = prev

    result = [
        (round(num / scale, precision), count_map[num])
        for num in sorted(count_map)
    ]
    return result


def format_result(
    target_expr: str,
    target_value: float,
    mode: str,
    result: Optional[Sequence[Tuple[float, int]]]
) -> str:
    """
    Formats the result into a clean, human-readable string output.
    Aligns decimals, symbols, and values.
    """
    header = "=" * 25
    lines = [header]
    lines.append(f"{'Target:':>12} {target_expr}")
    lines.append(f"{'=':>12} {target_value:.9f}")
    lines.append(f"{'Mode:':>12} {mode}")
    lines.append("-" * 25)

    if not result:
        lines.append(f"{'Result:':>12} No valid combination found.")
        lines.append(header)
        return "\n".join(lines)

    lines.append(f"{'Result:':>12}")

    rate_strs = [f"{rate:.3f}".rstrip('0').rstrip('.') for rate, _ in result]
    qty_strs = [str(qty) for _, qty in result]
    products = [rate * qty for rate, qty in result]

    rate_width = max(len(s) for s in rate_strs)
    qty_width = max(len(s) for s in qty_strs)

    for rate_str, qty, total in zip(rate_strs, qty_strs, products):
        lines.append(
            f"{rate_str:>{rate_width}} * {int(qty):>{qty_width}} = {total:>6.2f}"
        )

    lines.append("-" * 25)
    total_sum = sum(products)
    lines.append(f"{'Total:':>12} {total_sum:.3f}")
    lines.append(header)

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Compute the closest sum (with breakdown) above a target expression using predefined values."
    )
    parser.add_argument(
        '--target',
        required=True,
        help='Target value as a float expression, e.g. "(4000/3)/45"'
    )
    parser.add_argument(
        '--mode',
        choices=['above', 'below'],
        default='above',
        help='Whether to find closest sum above or below the target (default: above)'
    )

    args = parser.parse_args()

    target_expr = args.target
    mode = args.mode

    try:
        target_value = eval(force_floats(target_expr))
    except Exception as e:
        raise ValueError(
            f"Invalid expression for --target: {target_expr}"
        ) from e

    result = closest_sum_with_breakdown(target_value, mode)
    print(format_result(target_expr, target_value, mode, result))


if __name__ == "__main__":
    main()
